# pages
# ---------------------------------------------------------------------------------------
class Page:
    def __init__(self, kind, a, b):
        self.kind, self.a, self.b = kind, a, b
        self.slug = self.number = self.title_html = self.title_text = None
        self.label = None
        self.parent = None
        self.children = []
        self.html = None              # rendered body, or None when not converted
        self.error = None
        self.footnotes = []
        self.math = []
        self.anchors = {}
        self.files = []


class Ctx:
    def __init__(self, src, aux, bib, figures):
        self.src, self.aux, self.bib, self.figures = src, aux, bib, figures
        self.review_items = []
        self.figure_list = []
        self._used = {}
        self.assets = {}              # figure label -> asset dict (for the landing page)
        path = os.path.join(REPO, '_port', 'interactives.json')
        self.interactives = {}        # LaTeX label -> list of interactive module names
        self.interactives_used = set()
        if os.path.exists(path):
            for it in json.load(open(path, encoding='utf-8'))['interactives']:
                self.interactives.setdefault(it['label'], []).append(it['module'])

    def interactive(self, label):
        """Web-layer placeholders for the interactive figures attached to a LaTeX label."""
        out = []
        for module in self.interactives.get(label, []):
            self.interactives_used.add((label, module))
            out.append(f'<aside class="dg-web dg-interactive" data-module="{module}" data-for="{esc(label)}" '
                       f'aria-label="Interactive figure"><div class="dg-interactive-bar"><span class="dg-badge">Interactive</span>'
                       f'</div><div class="dg-interactive-body"></div></aside>')
        return ''.join(out)

    def review(self, kind, pos, text):
        self.review_items.append({'kind': kind, 'where': self.src.where(pos), 'text': text})

    def figures_used(self, slug):
        return self._used.setdefault(slug, [])


HEAD_RE = re.compile(r'\\(chapter|section)(\*?)\s*(?=[\[{])')
LABEL_AFTER = re.compile(r'\s*\\label\{([^}]+)\}')
PREFIX = re.compile(r'^(chapter|appendix|section|subsection)_', re.I)


def label_slug(label: str) -> str:
    return slugify(PREFIX.sub('', PREFIX.sub('', label)))


def make_pages(src: source.Source, P: Parser):
    cuts = [m.start() for m in HEAD_RE.finditer(src.text)]
    front = Page('front', 0, cuts[0] if cuts else len(src.text))
    pages, chapter = [], None
    for a, b in zip(cuts, cuts[1:] + [len(src.text)]):
        m = HEAD_RE.match(src.text, a)
        page = Page(m.group(1), a, b)
        _, end = P.read_args('Om', m.end(), b, a)
        lab = LABEL_AFTER.match(src.text, end)
        page.label = lab.group(1) if lab else None
        page.title_span = (m.end(), end)
        if page.kind == 'chapter':
            chapter = page
        else:
            page.parent = chapter
            chapter.children.append(page)
        pages.append(page)
    return front, pages


def assign_slugs(pages, P, src):
    seen = set()
    for p in pages:
        title_src = src.text[p.title_span[0]:p.title_span[1]]
        base = label_slug(p.label) if p.label else slugify(re.sub(r'\\[A-Za-z]+|[{}$]', ' ', title_src))
        p.slug = f'{base}/index' if p.kind == 'chapter' else f'{posixpath.dirname(p.parent.slug)}/{base}'
        if p.slug in seen:
            raise SystemExit(f'two pages would get the same address: {p.slug}')
        seen.add(p.slug)


def render_page(p: Page, ctx: Ctx, P: Parser, records: dict):
    r = Renderer(ctx, p, P, records)
    nodes = P.parse(p.a, p.b)
    head = nodes[0]
    p.number = None if head.star else r.take(p.kind, p.a)
    p.title_html = r.inline(head.args[1])
    i = 1
    while i < len(nodes) and (isinstance(nodes[i], Cmd) and nodes[i].name == 'label'
                              or isinstance(nodes[i], Text) and not nodes[i].s.strip()):
        if isinstance(nodes[i], Cmd):
            r.anchors[nodes[i].args[0].strip()] = ''          # the page itself
        i += 1
    body = r.flow(nodes[i:])
    left = {c: q for c, q in records.items() if q and c in CHECKED}
    if left:
        raise ConvertError(f'numbering records not consumed: {left} (LaTeX numbered something the converter did not see)', p.a)
    p.html, p.footnotes, p.math, p.anchors = body, r.footnotes, r.math_log, r.anchors


# ---------------------------------------------------------------------------------------
# output
# ---------------------------------------------------------------------------------------
def rel(from_slug: str, target: str) -> str:
    return posixpath.relpath(target, posixpath.dirname(from_slug) or '.')


def resolve(html: str, page: Page, ctx: Ctx, where: dict) -> str:
    def ref(m):
        label, style = m.group(1), m.group(2)
        info = ctx.aux.get(label)
        if info is None:
            ctx.review('undefined-ref', page.a, f'{label} (on page {page.slug})')
            return '<span class="dg-inprep" title="This part of the notes is in preparation">in preparation</span>'
        num = esc(info['num'])
        if label in where:
            slug, frag = where[label]
            href = rel(page.slug, slug + '.html') + ('#' + frag if frag else '')
            if slug == page.slug:
                href = '#' + frag if frag else '#'
            a = f'<a class="dg-xref" href="{href}" data-kind="{info["kind"]}" data-label="{esc(label)}">{num}</a>'
        else:
            a = f'<span class="dg-xref dg-xref-pending" data-label="{esc(label)}">{num}</span>'
        return f'({a})' if style == 'eqref' else a

    def url(m):
        t = m.group(1)
        if t.startswith('figures/') or t.startswith('assets/'):
            return rel(page.slug, t)
        slug, _, frag = t.partition('#')
        return rel(page.slug, slug + '.html') + ('#' + frag if frag else '')

    html = re.sub('\x02R\\|([^|\x02]+)\\|([a-z]+)\x02', ref, html)
    return re.sub('\x02U\\|([^\x02]+)\x02', url, html)


def plain(html: str) -> str:
    """Title for <title>, the sidebar and search: tags dropped, math kept as its TeX source."""
    t = re.sub(r'<span class="math inline">\\\((.*?)\\\)</span>', r'$\1$', html)
    t = re.sub(r'\x02R\|([^|]+)\|[a-z]+\x02', lambda m: PLAIN_NUM.get(m.group(1), '…'), t)
    t = re.sub(r'<[^>]+>', '', t)
    return t.replace('&amp;', '&').replace('&lt;', '<').replace('&gt;', '>')


PLAIN_NUM: dict = {}


def kicker(p: Page) -> str:
    c = p if p.kind == 'chapter' else p.parent
    word = 'Appendix' if c.number and c.number[0].isalpha() else 'Chapter'
    if p.kind == 'chapter':
        return f'{word} {c.number}' if c.number else ''
    link = f'<a href="{rel(p.slug, c.slug + ".html")}">{c.title_html}</a>'
    return f'{word} {c.number} <span class="dg-sep">•</span> {link}'


def write_page(p: Page, ctx: Ctx, where: dict, order: list, files: set):
    num = f'<span class="dg-secnum">{p.number}</span> ' if p.number and p.kind == 'section' else ''
    head = (f'<header class="dg-head dg-head-{p.kind}"><p class="dg-kicker">{kicker(p)}</p>'
            f'<h1 class="dg-title">{num}{p.title_html}</h1></header>')
    body = p.html
    if p.footnotes:
        notes = ''.join(f'<div class="dg-fn" id="fn-{n}" role="doc-footnote"><a class="dg-fn-num" href="#fnref-{n}" '
                        f'aria-label="Back to the text">{n}</a><div class="dg-fn-body">{h}</div></div>'
                        for n, h in p.footnotes)
        body += f'\n<section class="dg-footnotes" role="doc-endnotes">{notes}</section>'
    if p.kind == 'chapter' and p.children:
        lis = ''.join(f'<li><a href="{rel(p.slug, c.slug + ".html")}"><span class="dg-secnum">{c.number}</span> '
                      f'{c.title_html}</a></li>' if c.html is not None else
                      f'<li class="dg-pending"><span class="dg-secnum">{c.number or ""}</span> {c.title_html or ""}</li>'
                      for c in p.children)
        body += f'\n<nav class="dg-web dg-chapter-sections" aria-label="Sections"><ul>{lis}</ul></nav>'
    k = order.index(p)
    prev = next((q for q in reversed(order[:k]) if q.html is not None), None)
    nxt = next((q for q in order[k + 1:] if q.html is not None), None)

    def navlink(q, cls, arrow):
        if q is None:
            return '<span></span>'
        n = f'<span class="dg-secnum">{q.number}</span> ' if q.number else ''
        return f'<a class="{cls}" href="{rel(p.slug, q.slug + ".html")}" rel="{cls[3:]}">{arrow}<span>{n}{q.title_html}</span></a>'
    body += (f'\n<nav class="dg-web dg-prevnext" aria-label="Previous and next page">'
             f'{navlink(prev, "dg-prev", "<span aria-hidden=\"true\">←</span> ")}'
             f'{navlink(nxt, "dg-next", "<span aria-hidden=\"true\">→</span> ")}</nav>')
    html = resolve(head + '\n' + body, p, ctx, where)

    title = (f'{p.number} ' if p.number else '') + plain(p.title_html)
    src_files = ', '.join(sorted({ctx.src.loc(o)[0] for o in (p.a, p.b - 1)}))
    out = ['---', 'title: ' + json.dumps(title, ensure_ascii=False), '---', '',
           f'{MARK} from {src_files}.', '     Do not edit this file: edit the LaTeX notes and re-run the converter. -->', '']
    for seg in re.split('(\x01H\\d\\|[^\x01]*\x01)', html):
        if seg.startswith('\x01H'):
            level, hid, h = seg[2:-1].split('|', 2)
            tick = '``' if '`' in h else '`'
            out += ['', '#' * int(level) + f' {tick}{h}{tick}{{=html}} {{#{hid}}}', '']
        elif seg.strip():
            out += ['```{=html}', seg.strip('\n'), '```']
    path = os.path.join(OUT, p.slug + '.qmd')
    os.makedirs(os.path.dirname(path), exist_ok=True)
    text = '\n'.join(out) + '\n'
    files.add(path)
    if not os.path.exists(path) or open(path, encoding='utf-8').read() != text:
        open(path, 'w', encoding='utf-8').write(text)


def write_sidebar(order: list, files: set):
    def item(p, indent):
        t = json.dumps((f'{p.number} ' if p.number else '') + plain(p.title_html or '…'), ensure_ascii=False)
        pad = ' ' * indent
        if p.kind == 'chapter':
            lines = [f'{pad}- section: {t}']
            if p.html is not None:
                lines.append(f'{pad}  href: {COURSE}/{p.slug}.qmd')
            lines.append(f'{pad}  contents:')
            kids = [l for c in p.children for l in item(c, indent + 4)]
            return lines + (kids or [f'{pad}    []'])
        if p.html is None:
            return [f'{pad}- text: {t}']
        return [f'{pad}- text: {t}', f'{pad}  href: {COURSE}/{p.slug}.qmd']

    chapters = [p for p in order if p.kind == 'chapter']
    main = [p for p in chapters if not (p.number or '?')[0].isalpha()]
    apps = [p for p in chapters if (p.number or '?')[0].isalpha()]
    y = ['# GENERATED by _port/convert/build.py. Do not edit: re-run the converter.',
         'website:', '  sidebar:', '    - id: diffgeo-gr', '      title: "From Differential Geometry to General Relativity"',
         '      style: docked', '      collapse-level: 1', '      contents:',
         f'        - text: "Course home"', f'          href: {COURSE}/index.qmd']
    for p in main:
        y += item(p, 8)
    if apps:
        y += ['        - section: "Appendices"', '          contents:']
        for p in apps:
            y += item(p, 12)
    path = os.path.join(OUT, '_sidebar.yml')
    files.add(path)
    open(path, 'w', encoding='utf-8').write('\n'.join(y) + '\n')


def write_partials(front, pages, ctx, P, files):
    """Generated fragments included by the hand-written landing page (index.qmd)."""
    import cover
    texts = cover.extract(ctx.src.text[front.a:front.b])
    r = Renderer(ctx, front, None, {})
    h = {}
    for k, tex in texts.items():
        pp = Parser(tex)
        h[k] = r.inline(pp.parse(0, len(tex))) if k != 'email' else esc(tex)
    cover_html = (f'<header class="dg-cover"><h1 class="dg-cover-title">{h["title"]}</h1>'
                  f'<p class="dg-cover-subtitle">{h["subtitle"]}</p><div class="dg-cover-rule"></div>'
                  f'<p class="dg-cover-author">{h["author"]}</p>'
                  f'<p class="dg-cover-affiliation">{h["affiliation"]}<br>{h["address"]}</p>'
                  f'<p class="dg-cover-email"><a href="mailto:{h["email"]}"><code class="dg-code">{h["email"]}</code></a></p></header>')
    dedication = (f'<section class="dg-epigraph"><blockquote><p class="dg-epigraph-quote">{h["quote"]}</p>'
                  f'<footer><span class="dg-epigraph-author">{h["quote_author"]}</span><br>'
                  f'<span class="dg-epigraph-source">{h["quote_source"]}</span></footer></blockquote></section>'
                  f'<section class="dg-dedication"><p>{h["dedication"]}</p></section>')
    lis = []
    for c in (p for p in pages if p.kind == 'chapter'):
        word = 'Appendix' if (c.number or '?')[0].isalpha() else 'Chapter'
        t = f'<span class="dg-contents-kicker">{word} {c.number}</span> <span class="dg-contents-title">{c.title_html}</span>'
        head = f'<a href="{c.slug}.html">{t}</a>' if c.html is not None else f'<span class="dg-pending">{t}</span>'
        subs = ''.join(f'<li><a href="{k.slug}.html"><span class="dg-secnum">{k.number}</span> {k.title_html}</a></li>'
                       if k.html is not None else
                       f'<li class="dg-pending"><span class="dg-secnum">{k.number or ""}</span> {k.title_html}</li>' for k in c.children)
        lis.append(f'<li class="dg-contents-chapter">{head}' + (f'<ul>{subs}</ul>' if subs else '') + '</li>')
    contents = f'<nav class="dg-contents" aria-label="Contents"><ol>{"".join(lis)}</ol></nav>'
    a = ctx.assets.get('fig_roadmap_master')
    roadmap = ''
    if a:
        roadmap = (f'<div class="dg-landing-map"><div class="dg-paper" data-map="1"><img src="{a["src"]}" alt="" '
                   f'width="{a["width"]}" height="{a["height"]}" data-kind="{a["kind"]}"></div></div>')
    index_page = Page('front', 0, 0)
    index_page.slug = 'index'
    os.makedirs(os.path.join(OUT, '_generated'), exist_ok=True)
    for name, html in (('cover', cover_html), ('dedication', dedication), ('contents', contents), ('roadmap', roadmap)):
        html = resolve(html, index_page, ctx, {})
        path = os.path.join(OUT, '_generated', name + '.qmd')
        files.add(path)
        open(path, 'w', encoding='utf-8').write(f'{MARK} from main.tex. Do not edit: re-run the converter. -->\n\n'
                                                f'```{{=html}}\n{html}\n```\n')


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument('--status', action='store_true')
    ap.add_argument('--strict', action='store_true')
    ap.add_argument('--no-figures', action='store_true', help='do not build figure assets (placeholders)')
    args = ap.parse_args()

    src = source.load(SRC)
    P = Parser(src.text)
    aux = read_aux(os.path.join(SRC, 'main.aux'))
    bib = read_bbl(os.path.join(SRC, 'main.bbl'))
    records = read_records(os.path.join(SRC, 'main.port'), src)
    for k, v in aux.items():
        PLAIN_NUM[k] = v['num']

    if args.no_figures or args.status:
        class Stub:
            def graphic(self, path, name): return {'src': f'figures/{name}.svg', 'width': 800, 'height': 500, 'kind': 'stub'}
            def tex(self, snippet, name, tw=16.0): return {'src': f'figures/{name}.svg', 'width': 800, 'height': 500, 'kind': 'stub', 'width_frac': 1.0}
        figures = Stub()
    else:
        from figures import Figures
        figures = Figures(REPO, src.preamble, os.path.join(SRC, 'main.aux'))
    ctx = Ctx(src, aux, bib, figures)
    for k, v in bib.items():                      # author names of the bibliography labels, as text
        r = Renderer(ctx, Page('front', 0, 0), Parser(v['author_tex']), {})
        v['author'] = r.inline(Parser(v['author_tex']).parse(0, len(v['author_tex'])))

    front, pages = make_pages(src, P)
    assign_slugs(pages, P, src)
    starts = [p.a for p in pages]
    per_page = [dict() for _ in pages]
    for off, counter, num in records:
        k = bisect.bisect_right(starts, off) - 1
        if k >= 0:
            per_page[k].setdefault(counter, []).append(num)

    for p, rec in zip(pages, per_page):
        try:
            render_page(p, ctx, P, rec)
        except ConvertError as e:
            p.error = f'{src.where(e.pos if e.pos is not None else p.a)}: {e.msg}'
            # the heading is still needed for the sidebar
            p.number = next((n for o, c, n in records if c == p.kind and o >= p.a), None)
            try:
                title = P.read_args('Om', p.title_span[0], p.b, p.a)[0][1]
                p.title_html = Renderer(ctx, p, P, {}).inline(title)
            except ConvertError:
                p.title_html = '…'

    done = [p for p in pages if p.html is not None]
    print(f'{len(done)} of {len(pages)} pages convert')
    for p in pages:
        if p.error:
            print(f'  PENDING {p.number or "":6} {p.slug:60} {p.error}')
    report = {'pages': [{'slug': p.slug, 'number': p.number, 'kind': p.kind, 'title': plain(p.title_html or ''),
                         'converted': p.html is not None, 'error': p.error} for p in pages],
              'review': ctx.review_items}
    os.makedirs(os.path.join(REPO, '_port', '.work'), exist_ok=True)
    if args.status:
        return 1 if args.strict and len(done) < len(pages) else 0

    where = {}
    for p in done:
        for lab, frag in p.anchors.items():
            where[lab] = (p.slug, frag)
    files: set = set()
    for p in done:
        write_page(p, ctx, where, pages, files)
    write_sidebar(pages, files)
    write_partials(front, pages, ctx, P, files)
    for label, mods in ctx.interactives.items():
        for mod in mods:
            if (label, mod) not in ctx.interactives_used:
                print(f'  WARNING interactive "{mod}" is attached to label {label}, which no converted page defines')
    os.makedirs(os.path.join(OUT, 'assets'), exist_ok=True)
    labels = {lab: {'url': slug + '.html' + ('#' + frag if frag else ''), 'num': aux[lab]['num'], 'kind': aux[lab]['kind']}
              for lab, (slug, frag) in where.items() if lab in aux}
    json.dump(labels, open(os.path.join(OUT, 'assets', 'labels.json'), 'w', encoding='utf-8'),
              ensure_ascii=False, separators=(',', ':'), sort_keys=True)
    # remove generated pages that no longer exist in the notes
    for root, _, names in os.walk(OUT):
        for n in names:
            path = os.path.join(root, n)
            if n.endswith('.qmd') and path not in files and MARK in open(path, encoding='utf-8').read(400):
                os.remove(path)
    report['math'] = [{'page': p.slug, 'tex': t} for p in done for t in p.math]
    report['review'] = ctx.review_items
    json.dump(report, open(os.path.join(REPO, '_port', '.work', 'report.json'), 'w', encoding='utf-8'),
              ensure_ascii=False, indent=1)
    return 1 if args.strict and len(done) < len(pages) else 0


if __name__ == '__main__':
    sys.exit(main())
