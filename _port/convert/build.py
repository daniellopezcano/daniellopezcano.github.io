def main_text(c: Page) -> bool:
    return bool(c.number) and c.number[0].isdigit()


def chapter_data(pages: list, ctx: Ctx) -> dict:
    """chapter page -> {'related': [(appendix, [(item, [pages of the chapter])])], 'back': {item: [main-text pages]},
    'map': figure label or None, 'counts': {figure label: badges into the chapter}} (D38).
    An appendix item (section page of Appendix B or C) is connected with a main-text page when one of the two
    refers to a label that lives on the other. Pages that do not convert yet (D16) take their labels and
    references from the source."""
    owner, refs = {}, {}
    for p in pages:
        if p.html is not None:
            labs, rs = list(p.anchors), p.refs
        else:
            labs = [m.group(1).strip() for m in SRC_LABEL.finditer(ctx.src.text, p.a, p.b)]
            rs = [m.group(1).strip() for m in SRC_REF.finditer(ctx.src.text, p.a, p.b)]
        for lab in labs:
            owner.setdefault(lab, p)
        refs[p] = set(rs)
    order = {p: i for i, p in enumerate(pages)}
    chapters = [p for p in pages if p.kind == 'chapter']
    apps = [c for c in chapters if c.number in RELATED]
    text = [q for q in pages if main_text(chapter_of(q))]
    pairs = {}                                            # item -> main-text pages connected with it
    for app in apps:
        for y in app.children:
            pairs[y] = sorted((q for q in text if any(owner.get(lab) is y for lab in refs[q])
                               or any(owner.get(lab) is q for lab in refs[y])), key=order.get)
    data = {c: {'related': [], 'back': {}, 'map': None, 'counts': {}} for c in chapters}
    for c in chapters:
        if main_text(c):
            for app in apps:
                its = [(y, [q for q in pairs[y] if chapter_of(q) is c]) for y in app.children]
                its = [(y, qs) for y, qs in its if qs]
                if its:
                    data[c]['related'].append((app, its))
        elif c.number in RELATED:
            data[c]['back'] = {y: pairs[y] for y in c.children if pairs[y]}
    # roadmap: among the detailed roadmaps (the figures of the master roadmap's section, except the master one),
    # the one with the most badges pointing into the chapter, at least two; a tie goes to the earlier figure
    master = ctx.captions.get(MASTER_MAP)
    if master:
        home = chapter_of(next(p for p in pages if p.slug == master['page']))
        maps = [f for f, v in ctx.captions.items() if v['page'] == master['page'] and f != MASTER_MAP]
        badges = {}
        for f in maps:
            path = os.path.join(OUT, ctx.assets[f]['src'])
            badges[f] = BADGE.findall(open(path, encoding='utf-8').read()) if os.path.exists(path) else []
            if not badges[f]:
                print(f'  WARNING roadmap {f}: no badges found in {os.path.relpath(path, REPO)}')
        for c in chapters:
            if c is home:                                 # it holds the roadmaps
                continue
            n = {f: sum(1 for lab in badges[f] if lab in owner and chapter_of(owner[lab]) is c) for f in maps}
            best = max(maps, key=lambda f: (n[f], -maps.index(f)), default=None)
            data[c]['counts'] = n
            if best and n[best] >= 2:
                data[c]['map'] = best
    return data


def print_chapters(data: dict, ctx: Ctx) -> None:
    """The computed table behind the chapter opening pages (build.py --chapters)."""
    print('chapter opening pages (D38): roadmap (badges into the chapter per detailed roadmap) and related items')
    for c, d in data.items():
        num = lambda q: q.number or '?'
        counts = ', '.join(f'{ctx.captions[f]["num"]}: {k}' for f, k in d['counts'].items())
        fig = f'Figure {ctx.captions[d["map"]]["num"]} ({d["map"]})' if d['map'] else '-'
        print(f'  {num(c):>2} {plain(c.title_html or "")[:34]:34} roadmap {fig}' + (f'   [{counts}]' if counts else ''))
        for app, its in d['related']:
            print(f'       {app.number}: ' + '  '.join(f'{num(y)} ({", ".join(num(q) for q in qs)})' for y, qs in its))
        if d['back']:
            print('       ' + '  '.join(f'{num(y)} <- {", ".join(num(q) for q in qs)}' for y, qs in d['back'].items()))


def chapter_web(p: Page, d: dict, ctx: Ctx, where: dict) -> str:
    """Web layer of a chapter opening page (D38): its sections, the related appendix items, the roadmap.
    Titles carry placeholders: resolve() runs on the result."""
    def numtitle(q):
        return f'<span class="dg-secnum">{q.number or ""}</span> {nolinks(q.title_html or "…")}'

    def head(c, tag, link, extra=''):
        word = 'Appendix' if c.number and c.number[0].isalpha() else 'Chapter'
        t = f'<span class="dg-contents-kicker">{word} {c.number}</span> <span class="dg-contents-title">{nolinks(c.title_html)}</span>'
        if link:
            t = f'<a href="{rel(p.slug, c.slug + ".html")}">{t}</a>'
        return f'<{tag} class="dg-chapter-card-head"{extra}>{t}</{tag}>'

    def connected(qs):
        # each page number is a small chip (web layer): a link, or, for this page itself, a chip without one;
        # chips wrap between one another, so a wrapped line never begins with a separator
        out = []
        for q in qs:
            if q is p:
                out.append(f'<span class="dg-chip dg-related-here" aria-current="page">{q.number}</span>')
            elif q.html is None:
                out.append(f'<span class="dg-chip dg-pending">{q.number}</span>')
            else:
                out.append(f'<a class="dg-chip" href="{rel(p.slug, q.slug + ".html")}">{q.number}</a>')
        return (f' <span class="dg-related-pages" role="group" aria-label="{INTERFACE_RELATED}" title="{INTERFACE_RELATED}">'
                + ''.join(out) + '</span>')

    def item(y, extra='', mark=''):
        if y.html is None:
            return f'<li class="dg-pending"><span class="dg-related-item">{numtitle(y)}</span>{extra}</li>'
        return f'<li><a class="dg-related-item" href="{rel(p.slug, y.slug + ".html")}">{numtitle(y)}{mark}</a>{extra}</li>'

    cards = []
    if p.children:
        # beside the related items, the card is headed like them (the chapter's own number and title); alone,
        # it sits right under the page's title and needs no head. The sections carry the "read" marks (D40).
        lis = ''.join(item(c, connected(d['back'][c]) if c in d['back'] else '', shell.readmark()) for c in p.children)
        cards.append(f'<nav class="dg-chapter-card dg-chapter-sections" aria-label="Sections">'
                     f'{head(p, "p", False) if d["related"] else ""}<ul>{lis}</ul></nav>')
    if d['related']:
        groups = ''.join(f'<nav class="dg-chapter-card" aria-labelledby="dg-related-{app.number}">'
                         f'{head(app, "h2", True, f" id=\"dg-related-{app.number}\"")}'
                         f'<ul>{"".join(item(y, connected(qs)) for y, qs in its)}</ul></nav>' for app, its in d['related'])
        cards.append(f'<div class="dg-chapter-related">{groups}</div>')
    out = ''
    if cards:
        out = f'\n<div class="dg-web dg-chapter-web{" dg-two" if len(cards) == 2 else ""}">{"".join(cards)}</div>'
    fid = d['map']
    if fid and fid in where:
        cap, a = ctx.captions[fid], ctx.assets[fid]
        slug, frag = where[fid]
        num = f'<a class="dg-fignum" href="{rel(p.slug, slug + ".html")}#{frag}">Figure {cap["num"]}:</a>'
        out += (f'\n<div class="dg-web dg-chapter-map"><figure class="dg-figure">'
                f'<div class="dg-paper" data-map="lazy" data-ring="chapter" style="--dg-frac:{cap["frac"]:.3f}">'
                f'<img src="{rel(p.slug, a["src"])}" alt="Figure {cap["num"]}" width="{a["width"]}" height="{a["height"]}" '
                f'loading="lazy" decoding="async" data-kind="{a["kind"]}"></div>'
                f'<figcaption>{num} {cap["caption"]}</figcaption></figure></div>')
    return out


def write_page(p: Page, ctx: Ctx, where: dict, order: list, files: set, cfg: dict, search: list, chapters: dict):
    num = f'<span class="dg-secnum">{p.number}</span> ' if p.number and p.kind == 'section' else ''
    head = (f'<header class="dg-head dg-head-{p.kind}"><p class="dg-kicker">{kicker(p)}</p>'
            f'<h1 class="dg-title">{num}{p.title_html}</h1></header>')
    body = p.html
    if p.footnotes:
        # the number links back to the mark; a \footnotetext whose mark the notes place by hand (inside
        # math, as \hyperlink to the footnote) has no mark element to return to: the number is plain text
        def fnnum(n):
            if f'id="fnref-{n}"' in body:
                return f'<a class="dg-fn-num" href="#fnref-{n}" aria-label="Footnote {n}, back to the text">{n}</a>'   # the name holds the visible number (WCAG 2.5.3)
            return f'<span class="dg-fn-num">{n}</span>'
        notes = ''.join(f'<div class="dg-fn" id="fn-{n}">{fnnum(n)}<div class="dg-fn-body">{h}</div></div>'
                        for n, h in p.footnotes)
        body += f'\n<div class="dg-footnotes">{notes}</div>'
    if p.kind == 'chapter':
        body += chapter_web(p, chapters[p], ctx, where)
    k = order.index(p)
    prev = next((q for q in reversed(order[:k]) if q.html is not None), None)
    nxt = next((q for q in order[k + 1:] if q.html is not None), None)

    def navlink(q, cls, arrow):
        if q is None:
            return '<span></span>'
        n = f'<span class="dg-secnum">{q.number}</span> ' if q.number else ''
        return f'<a class="{cls}" href="{rel(p.slug, q.slug + ".html")}" rel="{cls[3:]}">{arrow}<span>{n}{nolinks(q.title_html)}</span></a>'
    if p.kind == 'section':
        body += '\n' + shell.readtoggle()                 # D40: the "read" toggle, next to previous/next
    body += (f'\n<nav class="dg-web dg-prevnext" aria-label="Previous and next page">'
             f'{navlink(prev, "dg-prev", "<span aria-hidden=\"true\">←</span> ")}'
             f'{navlink(nxt, "dg-next", "<span aria-hidden=\"true\">→</span> ")}</nav>')
    head, body = resolve(head, p, ctx, where), resolve(body, p, ctx, where)

    title = (f'{p.number} ' if p.number else '') + plain(p.title_html)
    href = f'{COURSE}/{p.slug}.html'
    search += search_entries(href, re.sub(r'\$(.+?)\$', r'\\(\1\\)', title), body)    # math delimited as in the text
    chap = p if p.kind == 'chapter' else p.parent
    home = rel(p.slug, 'index.html')
    crumbs = [f'<a href="{home}">{esc(shell.course_label(cfg))}</a>']
    if chap is not p:
        crumbs.append(f'<a href="{rel(p.slug, chap.slug + ".html")}">{numbered(chap)}{nolinks(chap.title_html)}</a>')
    crumbs.append(f'<span aria-current="page">{numbered(p)}{nolinks(p.title_html)}</span>')
    crumbs = [resolve(c, p, ctx, where) for c in crumbs]
    tree = resolve(course_tree(p, order, outline(p.html)), p, ctx, where)
    src_files = ', '.join(sorted({ctx.src.loc(o)[0] for o in (p.a, p.b - 1)}))
    text = shell.document(cfg=cfg, slug=p.slug, source=src_files,
                          title=f'{title.replace("$", "")} – {shell.COURSE_TITLE} – {shell.SITE_NAME}',
                          desc=shell.description(text_of(body)), crumbs=crumbs, tree=tree,
                          main=glue(headings(head + '\n' + body)), pos=(k + 1) / len(order), chapter=p.kind == 'chapter')
    write(os.path.join(OUT, p.slug + '.html'), text, files)


CHANGED: set = set()                                 # pages whose bytes this run changed (for lastmod.json)


def write(path: str, text: str, files: set):
    os.makedirs(os.path.dirname(path), exist_ok=True)
    files.add(path)
    if not os.path.exists(path) or open(path, encoding='utf-8').read() != text:
        open(path, 'w', encoding='utf-8').write(text)
        CHANGED.add(path)


def write_lastmod(files: set):
    """assets/lastmod.json: page (relative to the course) -> time its bytes last changed, in the sitemap's
    format. A page this run did not change keeps its value, so a rebuild without changes leaves the file,
    and the sitemap that post_render.py writes from it, untouched. A page new to the file and unchanged
    by this run starts from its file's modification time."""
    import datetime
    path = os.path.join(OUT, 'assets', 'lastmod.json')
    old = json.load(open(path, encoding='utf-8')) if os.path.exists(path) else {}
    stamp = lambda t: t.strftime('%Y-%m-%dT%H:%M:%S.') + f'{t.microsecond // 1000:03d}Z'
    now = stamp(datetime.datetime.now(datetime.timezone.utc))
    new = {}
    for f in sorted(files):
        if not f.endswith('.html'):
            continue
        rel_ = os.path.relpath(f, OUT).replace(os.sep, '/')
        if f in CHANGED and rel_ in old:
            new[rel_] = now
        elif rel_ in old:
            new[rel_] = old[rel_]
        else:
            new[rel_] = stamp(datetime.datetime.fromtimestamp(os.stat(f).st_mtime, tz=datetime.timezone.utc))
    text = json.dumps(new, indent=0, sort_keys=True) + '\n'
    if not os.path.exists(path) or open(path, encoding='utf-8').read() != text:
        open(path, 'w', encoding='utf-8').write(text)


def write_landing(front, pages, ctx, files, cfg: dict, search: list):
    """The landing page: templates/landing.html (hand-written) with fragments generated from main.tex."""
    import cover
    texts = cover.extract(ctx.src.text[front.a:front.b])
    r = Renderer(ctx, front, None, {})
    h = {}
    for k, tex in texts.items():
        pp = Parser(tex)
        h[k] = r.inline(pp.parse(0, len(tex))) if k != 'email' else esc(tex)
    cover_html = (f'<header class="dg-cover"><h1 class="dg-cover-title">{h["title"]}</h1>'
                  f'<p class="dg-cover-subtitle">{h["subtitle"]}</p><div class="dg-cover-rule"></div>'
                  f'<p class="dg-cover-author">{h["author"]}</p>'
                  f'<p class="dg-cover-affiliation">{h["affiliation"]}<br>{h["address"]}</p>'
                  f'<p class="dg-cover-email"><a href="mailto:{h["email"]}"><code class="dg-code">{h["email"]}</code></a></p></header>')
    dedication = (f'<section class="dg-epigraph"><blockquote><p class="dg-epigraph-quote">{h["quote"]}</p>'
                  f'<footer><span class="dg-epigraph-author">{h["quote_author"]}</span><br>'
                  f'<span class="dg-epigraph-source">{h["quote_source"]}</span></footer></blockquote></section>'
                  f'<section class="dg-dedication"><p>{h["dedication"]}</p></section>')
    lis = []
    for c in (p for p in pages if p.kind == 'chapter'):
        if c.part_html:                 # a part title of the notes' contents ("Appendices")
            lis.append(f'<li class="dg-contents-part">{c.part_html}</li>')
        word = 'Appendix' if (c.number or '?')[0].isalpha() else 'Chapter'
        t = f'<span class="dg-contents-kicker">{word} {c.number}</span> <span class="dg-contents-title">{nolinks(c.title_html)}</span>'
        head = f'<a href="{c.slug}.html">{t}</a>' if c.html is not None else f'<span class="dg-pending">{t}</span>'
        subs = ''.join(f'<li><a href="{k.slug}.html"><span class="dg-secnum">{k.number}</span> {nolinks(k.title_html)}{shell.readmark()}</a></li>'
                       if k.html is not None else
                       f'<li class="dg-pending"><span class="dg-secnum">{k.number or ""}</span> {k.title_html}</li>' for k in c.children)
        lis.append(f'<li class="dg-contents-chapter">{head}' + (f'<ul>{subs}</ul>' if subs else '') + '</li>')
    contents = f'<nav class="dg-contents" aria-label="Contents"><ol>{"".join(lis)}</ol></nav>'
    a = ctx.assets.get('fig_roadmap_master')
    roadmap = ''
    if a:
        roadmap = (f'<div class="dg-landing-map" id="dg-roadmap"><div class="dg-paper" data-map="1"><img src="{a["src"]}" alt="" '
                   f'width="{a["width"]}" height="{a["height"]}" data-kind="{a["kind"]}"></div></div>')
    index_page = Page('front', 0, 0)
    index_page.slug = 'index'
    frags = {name: resolve(x, index_page, ctx, {}) for name, x in
             (('cover', cover_html), ('dedication', dedication), ('contents', contents), ('roadmap', roadmap))}
    main = glue(shell.landing_main(frags))
    label = shell.course_label(cfg)
    search.insert(0, {'objectID': f'{COURSE}/index.html', 'href': f'{COURSE}/index.html', 'title': shell.COURSE_TITLE,
                      'section': '', 'text': text_of(frags['cover'] + frags['dedication'])})
    text = shell.document(cfg=cfg, slug='index', source='main.tex and _port/convert/templates/landing.html',
                          title=f'{shell.COURSE_TITLE} – {shell.SITE_NAME}', desc=shell.description(text_of(frags['cover'])),
                          crumbs=[f'<span aria-current="page">{esc(label)}</span>'], tree='', main=main, pos=0.0,
                          landing=True)
    write(os.path.join(OUT, 'index.html'), text, files)


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument('--status', action='store_true')
    ap.add_argument('--strict', action='store_true')
    ap.add_argument('--chapters', action='store_true', help='print the data of the chapter opening pages (D38); writes nothing')
    ap.add_argument('--no-figures', action='store_true', help='do not build figure assets (placeholders)')
    args = ap.parse_args()

    src = source.load(SRC)
    P = Parser(src.text)
    aux = read_aux(os.path.join(SRC, 'main.aux'))
    bib = read_bbl(os.path.join(SRC, 'main.bbl'))
    records = read_records(os.path.join(SRC, 'main.port'), src)
    for k, v in aux.items():
        PLAIN_NUM[k] = v['num']
        PLAIN_NUM[(k, 'page')] = v['page']

    if args.no_figures or args.status or args.chapters:
        class Stub:
            def graphic(self, path, name): return {'src': f'figures/{name}.svg', 'width': 800, 'height': 500, 'kind': 'stub'}
            def tex(self, snippet, name, tw=16.0): return {'src': f'figures/{name}.svg', 'width': 800, 'height': 500, 'kind': 'stub', 'width_frac': 1.0}
        figures = Stub()
    else:
        from figures import Figures
        figures = Figures(REPO, src.preamble, os.path.join(SRC, 'main.aux'))
    ctx = Ctx(src, aux, bib, figures)
    for k, v in bib.items():                      # author names of the bibliography labels, as text
        r = Renderer(ctx, Page('front', 0, 0), Parser(v['author_tex']), {})
        v['author'] = r.inline(Parser(v['author_tex']).parse(0, len(v['author_tex'])))

    front, pages = make_pages(src, P)
    assign_slugs(pages, P, src)
    starts = [p.a for p in pages]
    per_page = [dict() for _ in pages]
    for off, counter, num in records:
        k = bisect.bisect_right(starts, off) - 1
        if k >= 0:
            per_page[k].setdefault(counter, []).append(num)

    for p, rec in zip(pages, per_page):
        try:
            render_page(p, ctx, P, rec)
        except ConvertError as e:
            p.error = f'{src.where(e.pos if e.pos is not None else p.a)}: {e.msg}'
            # the heading is still needed for the sidebar
            p.number = next((n for o, c, n in records if c == p.kind and o >= p.a), None)
            try:
                title = P.read_args('Om', p.title_span[0], p.b, p.a)[0][1]
                p.title_html = Renderer(ctx, p, P, {}).inline(title)
            except ConvertError:
                p.title_html = '…'

    part_titles(pages, ctx, P)
    done = [p for p in pages if p.html is not None]
    print(f'{len(done)} of {len(pages)} pages convert')
    for p in pages:
        if p.error:
            print(f'  PENDING {p.number or "":6} {p.slug:60} {p.error}')
    report = {'pages': [{'slug': p.slug, 'number': p.number, 'kind': p.kind, 'title': plain(p.title_html or ''),
                         'converted': p.html is not None, 'error': p.error} for p in pages],
              'review': ctx.review_items}
    os.makedirs(os.path.join(REPO, '_port', '.work'), exist_ok=True)
    chapters = chapter_data(pages, ctx)
    if args.chapters:
        print_chapters(chapters, ctx)
    if args.status or args.chapters:
        return 1 if args.strict and len(done) < len(pages) else 0

    where = {}
    for p in done:
        for lab, frag in p.anchors.items():
            where[lab] = (p.slug, frag)
    cfg = shell.site_config()
    shell.subset_fonts(os.path.join(OUT, 'assets', 'fonts'))
    files: set = set()
    search: list = []
    for p in done:
        write_page(p, ctx, where, pages, files, cfg, search, chapters)
    write_landing(front, pages, ctx, files, cfg, search)
    for label, mods in ctx.interactives.items():
        for mod in mods:
            if (label, mod) not in ctx.interactives_used:
                print(f'  WARNING interactive "{mod}" is attached to label {label}, which no converted page defines')
    os.makedirs(os.path.join(OUT, 'assets'), exist_ok=True)
    labels = {lab: {'url': slug + '.html' + ('#' + frag if frag else ''), 'num': aux[lab]['num'], 'kind': aux[lab]['kind']}
              for lab, (slug, frag) in where.items() if lab in aux}
    json.dump(labels, open(os.path.join(OUT, 'assets', 'labels.json'), 'w', encoding='utf-8'),
              ensure_ascii=False, separators=(',', ':'), sort_keys=True)
    json.dump(search, open(os.path.join(OUT, 'assets', 'search.json'), 'w', encoding='utf-8'),
              ensure_ascii=False, separators=(',', ':'))
    write_lastmod(files)
    # remove generated pages that no longer exist in the notes
    for root, _, names in os.walk(OUT):
        for n in names:
            path = os.path.join(root, n)
            if n.endswith('.html') and path not in files and MARK in open(path, encoding='utf-8').read(400):
                os.remove(path)
    report['math'] = [{'page': p.slug, 'tex': t} for p in done for t in p.math]
    report['review'] = ctx.review_items
    json.dump(report, open(os.path.join(REPO, '_port', '.work', 'report.json'), 'w', encoding='utf-8'),
              ensure_ascii=False, indent=1)
    return 1 if args.strict and len(done) < len(pages) else 0


if __name__ == '__main__':
    sys.exit(main())
