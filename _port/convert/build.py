def brace_groups(s: str, i: int) -> list[str]:
    """Top-level {..} groups of s starting at offset i."""
    out, depth, start = [], 0, None
    while i < len(s):
        c = s[i]
        if c == '\\':
            i += 2
            continue
        if c == '{':
            if depth == 0:
                start = i + 1
            depth += 1
        elif c == '}':
            depth -= 1
            if depth == 0:
                out.append(s[start:i])
        i += 1
    return out


def read_aux(path: str) -> dict:
    """label -> {'num', 'page', 'kind'} from \\newlabel{label}{{num}{page}{title}{anchor}{}}."""
    labels = {}
    for line in open(path, encoding='utf-8'):
        if not line.startswith('\\newlabel{'):
            continue
        g = brace_groups(line, len('\\newlabel'))
        inner = brace_groups(g[1], 0)
        if len(inner) < 4:
            continue
        kind = inner[3].split('.')[0]
        labels[g[0]] = {'num': inner[0], 'page': inner[1], 'kind': kind}
    return labels


def read_bbl(path: str) -> dict:
    """key -> {'author', 'year', 'entry'} from a natbib .bbl (\\bibitem[Author(Year)]{key})."""
    bib = {}
    if not os.path.exists(path):
        return bib
    txt = open(path, encoding='utf-8').read()
    for m in re.finditer(r'\\bibitem\[(.*?)\((\d{4}[a-z]?)\)[^\]]*\]\{([^}]+)\}(.*?)(?=\\bibitem|\\end\{thebibliography\})', txt, re.S):
        bib[m.group(3)] = {'author_tex': m.group(1), 'year': m.group(2), 'entry_tex': m.group(4).strip()}
    return bib


def read_records(path: str, src: source.Source) -> list[tuple[int, str, str]]:
    """(offset in src.text, counter, printed number) for every numbered object, in source order."""
    out = []
    for line in open(path, encoding='utf-8'):
        parts = line.rstrip('\n').split('|')
        if len(parts) != 4:
            continue
        counter, num, file, lineno = parts
        off = src.offset_of(file, int(lineno))
        if off is None:
            raise SystemExit(f'numbering record {line!r} points outside the included source')
        out.append((off, counter, num))
    return out


