#!/usr/bin/env python3
"""Generate the course pages from the LaTeX notes. Hand-written, part of the web port.

    python3 _port/convert/build.py            # regenerate every page that converts
    python3 _port/convert/build.py --status   # only report which pages convert / why not
    python3 _port/convert/build.py --strict   # exit 1 if any page does not convert

Inputs : the scratch copy of the notes compiled by _port/tex/build_scratch.sh
         (_port/.work/tex/src: sources + main.aux + main.port + main.bbl).
Outputs: notes/diffgeo-gr/**/*.qmd (generated, do not edit), _sidebar.yml,
         assets/labels.json, figures/, and _port/.work/report.json.
Everything hand-written for the web (index.qmd, _metadata.yml, assets/, the
interactive figures and _port/interactives.yml) is never touched.
"""
from __future__ import annotations
import argparse, bisect, json, os, posixpath, re, sys

HERE = os.path.dirname(os.path.abspath(__file__))
sys.path.insert(0, HERE)
import source                                        # noqa: E402
from texparse import Parser, ConvertError, Cmd, Text, Par   # noqa: E402
from render import Renderer, esc, slugify            # noqa: E402

REPO = os.path.abspath(os.path.join(HERE, '..', '..'))
SRC = os.path.join(REPO, '_port', '.work', 'tex', 'src')
COURSE = 'notes/diffgeo-gr'                          # course directory, relative to the repo root
OUT = os.path.join(REPO, COURSE)
MARK = '<!-- GENERATED by _port/convert/build.py'
CHECKED = ('chapter', 'section', 'subsection', 'subsubsection', 'figure', 'table', 'equation', 'footnote')


# ---------------------------------------------------------------------------------------
# data from the LaTeX build
# ---------------------------------------------------------------------------------------
def brace_groups(s: str, i: int) -> list[str]:
    """Top-level {..} groups of s starting at offset i."""
    out, depth, start = [], 0, None
    while i < len(s):
        c = s[i]
        if c == '\\':
            i += 2
            continue
        if c == '{':
            if depth == 0:
                start = i + 1
            depth += 1
        elif c == '}':
            depth -= 1
            if depth == 0:
                out.append(s[start:i])
        i += 1
    return out


def read_aux(path: str) -> dict:
    """label -> {'num', 'page', 'kind'} from \\newlabel{label}{{num}{page}{title}{anchor}{}}."""
    labels = {}
    for line in open(path, encoding='utf-8'):
        if not line.startswith('\\newlabel{'):
            continue
        g = brace_groups(line, len('\\newlabel'))
        inner = brace_groups(g[1], 0)
        if len(inner) < 4:
            continue
        kind = inner[3].split('.')[0]
        labels[g[0]] = {'num': inner[0], 'page': inner[1], 'kind': kind}
    return labels


def read_bbl(path: str) -> dict:
    """key -> {'author', 'year', 'entry'} from a natbib .bbl (\\bibitem[Author(Year)]{key})."""
    bib = {}
    if not os.path.exists(path):
        return bib
    txt = open(path, encoding='utf-8').read()
    for m in re.finditer(r'\\bibitem\[(.*?)\((\d{4}[a-z]?)\)[^\]]*\]\{([^}]+)\}(.*?)(?=\\bibitem|\\end\{thebibliography\})', txt, re.S):
        bib[m.group(3)] = {'author_tex': m.group(1), 'year': m.group(2), 'entry_tex': m.group(4).strip()}
    return bib


def read_records(path: str, src: source.Source) -> list[tuple[int, str, str]]:
    """(offset in src.text, counter, printed number) for every numbered object, in source order."""
    out = []
    for line in open(path, encoding='utf-8'):
        parts = line.rstrip('\n').split('|')
        if len(parts) != 4:
            continue
        counter, num, file, lineno = parts
        off = src.offset_of(file, int(lineno))
        if off is None:
            raise SystemExit(f'numbering record {line!r} points outside the included source')
        out.append((off, counter, num))
    return out


