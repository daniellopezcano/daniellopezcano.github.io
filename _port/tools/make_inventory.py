#!/usr/bin/env python3
"""Regenerate _port/INVENTORY.md from the scratch build of the notes.

    python3 _port/tools/make_inventory.py

Hand-written tool. The tables are computed from the LaTeX source and the build
products in _port/.work/tex/src; the prose sections are in this script.
"""
import collections, json, os, re, subprocess, sys
REPO = os.path.abspath(os.path.join(os.path.dirname(__file__), '..', '..'))
sys.path.insert(0, os.path.join(REPO, '_port', 'convert'))
import source, build                                    # noqa: E402
from texparse import Parser, CMDS, ENVS, RAW_ENVS, MATH_ENVS   # noqa: E402

SRC = build.SRC
src = source.load(SRC)
P = Parser(src.text)
aux = build.read_aux(os.path.join(SRC, 'main.aux'))
records = build.read_records(os.path.join(SRC, 'main.port'), src)
front, pages = build.make_pages(src, P)
build.assign_slugs(pages, P, src)
subprocess.run([sys.executable, os.path.join(REPO, '_port', 'convert', 'build.py'), '--status'], stdout=subprocess.DEVNULL)

out = []
w = out.append
w('# Inventory of the notes\n')
w('Generated by `_port/tools/make_inventory.py` from the scratch build of the LaTeX source '
  '(`_port/.work/tex/src`). Re-run it after the notes change; edit the prose in the script, not here.\n')
pdf = subprocess.run(['pdfinfo', os.path.join(SRC, 'main.pdf')], capture_output=True, text=True).stdout
npages = re.search(r'Pages:\s+(\d+)', pdf).group(1)
w(f'- Build: `main.tex`, XeLaTeX via latexmk, **{npages} pages**; {len(src.files)} source files included; '
  f'{len(src.text):,} characters of body source after comment removal.')
cnt = collections.Counter(c for _, c, _ in records)
w(f'- Numbered objects recorded by the instrumented build: {cnt["chapter"]} chapters (incl. appendices A–C), '
  f'{cnt["section"]} sections, {cnt["subsection"]} subsections, {cnt["subsubsection"]} subsubsections, '
  f'{cnt["figure"]} figures, {cnt["table"]} tables, {cnt["equation"]} numbered equations, {cnt["footnote"]} footnotes.')
w(f'- Labels in `main.aux`: {len(aux)}.\n')

# ------------------------------------------------------------------ files
w('## Source files\n')
w('### Included by `main.tex` (published)\n')
w('| File | Lines |\n|---|---:|')
for f in src.files:
    n = sum(1 for _ in open(os.path.join(SRC, f), encoding='utf-8'))
    w(f'| `{f}` | {n} |')
allt = sorted(os.path.relpath(os.path.join(d, x), SRC) for d, _, fs in os.walk(SRC) for x in fs
              if x.endswith('.tex') and x != 'port-hooks.tex')
w('\n### In the tree but NOT included (not published; picked up automatically once `main.tex` includes them)\n')
for f in allt:
    if f not in src.files:
        n = sum(1 for _ in open(os.path.join(SRC, f), encoding='utf-8'))
        w(f'- `{f}` ({n} lines)')
und = sorted({m for m in re.findall(r'\\(?:eq)?ref\*?\{([^}]+)\}', src.text) if m not in aux})
w(f'\nReferences that point into unpublished material ("??" in the PDF, "in preparation" on the web): '
  + ', '.join(f'`{u}`' for u in und) + '.\n')

# ------------------------------------------------------------------ structure
w('## Structure and page map\n')
w('Front matter (before Chapter 1): title page (TikZ), `Chapters/Copyrigh_page.tex` (copyright, MIT licence, '
  'FAPESP funding statement in two languages), table of contents, list of figures, quote + dedication page (TikZ), '
  '`Chapters/About_the_author.tex`.\n')
w('One web page per row. "Status" is what `build.py --status` says today.\n')
w('| No. | Title | Web page (`notes/diffgeo-gr/…`) | Source | Subsections | Figures | Eqs | Footnotes | Status |\n|---|---|---|---|---:|---:|---:|---:|---|')
status = {p['slug']: p for p in json.load(open(os.path.join(REPO, '_port', '.work', 'report.json')))['pages']} \
    if os.path.exists(os.path.join(REPO, '_port', '.work', 'report.json')) else {}
import bisect
starts = [p.a for p in pages]
per = [collections.Counter() for _ in pages]
num = {}
for off, c, n in records:
    k = bisect.bisect_right(starts, off) - 1
    if k >= 0:
        per[k][c] += 1
        if c == pages[k].kind and k not in num:
            num[k] = n
rep = subprocess.run([sys.executable, os.path.join(REPO, '_port', 'convert', 'build.py'), '--status'],
                     capture_output=True, text=True).stdout
pending = {l.split()[2] if len(l.split()) > 2 and '/' in l.split()[2] else l.split()[1]: l for l in rep.splitlines() if 'PENDING' in l}
for k, p in enumerate(pages):
    title = re.sub(r'\s+', ' ', src.text[p.title_span[0]:p.title_span[1]]).strip()
    title = re.sub(r'^\{|\}$', '', title)
    f = src.loc(p.a)[0]
    st = 'pending: ' + pending[p.slug].split(': ', 1)[-1][:70] if p.slug in pending else 'converts'
    c = per[k]
    w(f'| {num.get(k, "")} | {title} | `{p.slug}` | `{f}` | {c["subsection"] + c["subsubsection"]} | {c["figure"]} | '
      f'{c["equation"]} | {c["footnote"]} | {st} |')

# ------------------------------------------------------------------ figures
w('\n## Figures\n')
w('| No. | Label | Kind | Source |\n|---|---|---|---|')
figs = [(off, n) for off, c, n in records if c == 'figure']
for off, n in figs:
    f, line = src.loc(off)
    a = src.text.rfind('\\begin{figure}', 0, off)
    b = src.text.find('\\end{figure}', off)
    body = src.text[a:b] if a != -1 else ''
    if a == -1 or src.text.find('\\end{figure}', a) < off - 1 and '\\captionof' in src.text[max(0, off - 3000):off + 200]:
        body = src.text[max(0, off - 200):off + 600]
    g = re.search(r'\\includegraphics(?:\[[^\]]*\])?\{([^}]+)\}', body)
    kind = f'file `{g.group(1)}`' if g else 'TikZ (compiled to SVG)'
    lab = re.search(r'\\label\{([^}]+)\}', src.text[off:off + 6000]) if not re.search(r'\\label\{([^}]+)\}', body) else re.search(r'\\label\{([^}]+)\}', body)
    w(f'| {n} | `{lab.group(1) if lab else ""}` | {kind} | `{f}:{line}` |')
tik = len(re.findall(r'\\begin\{tikzpicture\}', src.text))
w(f'\n`tikzpicture` environments in the published source: {tik} (roadmaps, light cones, Newton–Cartan, integration charts, '
  f'metric variation, the Einstein–Hilbert flowchart, small diagrams in the appendices, and the cover / dedication / '
  f'copyright / about pages, which are full-page layouts).\n')

# ------------------------------------------------------------------ macros
w('## Commands and environments\n')
body = src.text
math_free = re.sub(r'\\begin\{tikzpicture\}.*?\\end\{tikzpicture\}', ' ', body, flags=re.S)
cmd = collections.Counter(re.findall(r'\\([A-Za-z@]+)', body))
env = collections.Counter(re.findall(r'\\begin\{([^}]+)\}', body))
w('The preamble of `main.tex` defines **no math macros**: only colours (`color_<name>_0/1/2`), the eleven pairs of '
  'defined-term macros (`\\blueone`/`\\bluetwo`, … `\\indigoone`/`\\indigotwo`: bold italic in that colour), '
  '`\\DLC` (author note), the font switches `\\runic` / `\\cunei`, the `motivationbox` tcolorbox and the `custompage` '
  'environment (pages of their own paper size, used for the roadmaps and the Einstein–Hilbert flowchart). '
  'Math is written in plain LaTeX + amsmath/mathtools/amssymb/mathrsfs.\n')
w('Defined-term macros in use: ' + ', '.join(f'`\\{c}one` ×{cmd[c + "one"]}' for c in
  ('blue', 'green', 'purple', 'orange', 'red', 'yellow', 'brown', 'teal', 'rose', 'olive', 'indigo') if cmd[c + 'one']) + '.\n')
w('Environments (all source, including inside math and TikZ): ' + ', '.join(f'`{k}` ×{v}' for k, v in env.most_common()) + '.\n')
w('Macros defined inside chapter files (not in the preamble): '
  + ', '.join(f'`{m}`' for m in sorted(set(re.findall(r'\\(?:newcommand\{?|def)(\\[A-Za-z@]+)', body)))) + '.\n')
runes = collections.Counter(re.findall(r'[\u16A0-\u16FF]', body))
w('Runic letters used as mathematical symbols (always written `\\textrm{\\runic X}`): '
  + ', '.join(f'{k} ×{v}' for k, v in runes.most_common()) + '.\n')
w(f'Text-mode commands the converter knows: {len(CMDS)}; environments: {len(ENVS)} parsed, {len(RAW_ENVS)} raw, '
  f'{len(MATH_ENVS)} math. Anything else stops the conversion of that page with file:line.\n')

w(HARD := '''## Hard to convert (and how each is handled)

1. **Runic symbols in math** (≈1000 uses, also in sub/superscripts and inside TikZ). Web: the literal Unicode rune inside `\\textrm{}`, the notes' own font served as a web font restricted to the runic block, MathJax told to wait for it. See DECISIONS D7.
2. **Numbering across ~75 pages** (chapters, sections, equations, figures, footnotes reset per chapter, appendix letters, hand-placed footnote marks in Ch. 8). Numbers are read from an instrumented LaTeX build, never recomputed. D5.
3. **TikZ**: four page-sized roadmaps with `\\ref*` badges, the Einstein–Hilbert flowchart (own macros, `\\captionof` inside `custompage`), nine smaller pictures. Compiled from source to SVG; badge references become links. D10.
4. **Front matter drawn in TikZ** (cover, quote/dedication): text is extracted for the landing page (`cover.py`); the copyright and about-the-author pages use page-layout macros (`\\cpheading`, `\\grantbadge`, `\\aboutstop`, overlays, a 16 MB background image) and need dedicated handlers.
5. **Math constructs MathJax may not support as written**: `array` column specs with `@{…}`, `tabular` inside display math, `\\xlongrightarrow[..]{..}`, `\\mathclap`. Checked expression by expression with `_port/tools/math_check.mjs`.
6. **References inside math** (`\\overset{\\text{Ch.~\\ref{..}}}{=}`) and **hand-placed footnote marks inside math** (`\\hyperlink{fn_…}{\\fnIntegralsFubini}`, Ch. 8).
7. **Tables**: four `tabular`s (two inside math), with rules and custom column specs.
8. **Item labels** (`\\item[(a)]`, `\\item[($\\Rightarrow$)]`, `\\item[1--2.]`) and `\\setcounter{enumi}` to resume a numbering.
9. **Unnumbered subsections** (`\\subsection*`, B.8), `\\pageref` (one use), `\\citealt`, the bibliography (natbib author–year, from the `.bbl`).
10. **Heavy figures**: several 3D matplotlib PDFs are 200 kB–2 MB of vector meshes; `main.pdf` itself is 27 MB.
''')
open(os.path.join(REPO, '_port', 'INVENTORY.md'), 'w', encoding='utf-8').write('\n'.join(out) + '\n')
print('wrote _port/INVENTORY.md', len(out), 'lines')
