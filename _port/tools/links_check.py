#!/usr/bin/env python3
"""Hand-written tool (DECISIONS D37, all-pages pass): every link of the course resolves.

    python3 _port/tools/links_check.py [--page <slug>]...      (exit code 0 = every link resolves)

Reads the rendered course in docs/notes/diffgeo-gr/ (static, no browser). For every generated page (or the
--page ones; a slug, 'index' for the landing page, or a prefix ending in '/'): each href/src of the page
(a, link, img, script, source, iframe; external http(s)/mailto/data/javascript addresses are skipped) must
point to an existing file under docs/, and when it has a fragment, to an element with that id in the target.
Also checked once (not per page): the URLs of assets/labels.json (used by the page script for references,
previews and the inlined roadmaps) and the hrefs of assets/search.json and docs/search.json.
Output: one line per broken link (`page: href  (why)`), then a count.
"""
import json, sys
from html.parser import HTMLParser
from pathlib import Path
from urllib.parse import urlsplit, unquote

REPO = Path(__file__).resolve().parents[2]
DOCS = REPO / 'docs'
COURSE = 'notes/diffgeo-gr'
ROOT = DOCS / COURSE
MARK = '<!-- GENERATED by _port/convert/build.py'
LINK_ATTRS = {'a': 'href', 'link': 'href', 'img': 'src', 'script': 'src', 'source': 'src', 'iframe': 'src', 'area': 'href'}


class Scan(HTMLParser):
    def __init__(self):
        super().__init__(convert_charrefs=True)
        self.ids, self.links = set(), []

    def handle_starttag(self, tag, attrs):
        a = dict(attrs)
        if a.get('id'):
            self.ids.add(a['id'])
        if tag == 'a' and a.get('name'):
            self.ids.add(a['name'])
        k = LINK_ATTRS.get(tag)
        if k and a.get(k) is not None:
            self.links.append(a[k])
        if tag == 'img' and a.get('srcset'):
            self.links += [c.strip().split()[0] for c in a['srcset'].split(',') if c.strip()]
    handle_startendtag = handle_starttag


_cache: dict = {}
def scan(path: Path) -> Scan:
    if path not in _cache:
        s = Scan()
        s.feed(path.read_text(encoding='utf-8', errors='replace'))
        _cache[path] = s
    return _cache[path]


def resolve(src: Path, href: str):
    """None if the link is fine (or external), else the reason it is broken."""
    if not href or href.startswith(('http://', 'https://', 'mailto:', 'data:', 'javascript:', 'tel:', '//')):
        return None
    u = urlsplit(href)
    target = src if not u.path else (src.parent / unquote(u.path)).resolve()
    if u.path.endswith('/') or (target.exists() and target.is_dir()):
        target = target / 'index.html'
    try:
        target.relative_to(DOCS)
    except ValueError:
        return 'points outside docs/'
    if not target.exists():
        return 'no such file'
    if u.fragment and target.suffix == '.html':
        if unquote(u.fragment) not in scan(target).ids:
            return f'no id "{unquote(u.fragment)}" in {target.relative_to(DOCS)}'
    return None


def pages():
    out = []
    for p in sorted(ROOT.rglob('*.html')):
        with open(p, encoding='utf-8', errors='replace') as f:
            if MARK in f.read(400):
                out.append(p)
    return out


def main(argv):
    want = [argv[i + 1].removesuffix('.html') for i, a in enumerate(argv) if a == '--page' and i + 1 < len(argv)]
    if not ROOT.exists():
        print(f'no {ROOT.relative_to(REPO)}: render or build first')
        return 2
    sel = pages()
    if want:
        slug = lambda p: p.relative_to(ROOT).with_suffix('').as_posix()
        sel = [p for p in sel if any(slug(p) == w or (w.endswith('/') and slug(p).startswith(w)) for w in want)]
        if not sel:
            print(f'no course page matches {", ".join(want)}')
            return 2
    bad, n = [], 0
    for p in sel:
        for href in dict.fromkeys(scan(p).links):          # each distinct link of a page once
            n += 1
            why = resolve(p, href)
            if why:
                bad.append(f'{p.relative_to(ROOT).as_posix()}: {href}  ({why})')
    if not want:
        labels = json.loads((ROOT / 'assets' / 'labels.json').read_text(encoding='utf-8'))
        for lab, v in sorted(labels.items()):
            n += 1
            why = resolve(ROOT / 'index.html', v['url'])
            if why:
                bad.append(f'assets/labels.json [{lab}]: {v["url"]}  ({why})')
        for idx, base in ((ROOT / 'assets' / 'search.json', DOCS / 'index.html'), (DOCS / 'search.json', DOCS / 'index.html')):
            if not idx.exists():
                continue
            for e in json.loads(idx.read_text(encoding='utf-8')):
                h = e.get('href', '')
                if not h.startswith(COURSE + '/'):
                    continue
                n += 1
                why = resolve(base, h)
                if why:
                    bad.append(f'{idx.relative_to(DOCS).as_posix()}: {h}  ({why})')
    for b in bad:
        print('BROKEN', b)
    print(f'{len(bad)} broken of {n} links checked on {len(sel)} pages')
    return 1 if bad else 0


if __name__ == '__main__':
    sys.exit(main(sys.argv[1:]))
