// Hand-written helper shared by the all-pages browser checks (a11y_check.mjs, page_check.mjs, navbar_check.mjs):
// the course (--course NAME, resolved through _port/convert/courses.py --json; default diffgeo-gr), the list of
// course pages in docs/, the --page filter, a small worker pool, the "page is ready" wait, and eachCourse(),
// which re-runs a tool once per course when it is called without --course (as math_check.mjs does).
// Not a check by itself.
import fs from 'node:fs';
import path from 'node:path';
import { spawnSync } from 'node:child_process';
import { fileURLToPath } from 'node:url';

export const REPO = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..', '..');
export const COURSES = JSON.parse(spawnSync('python3', [path.join(REPO, '_port', 'convert', 'courses.py'), '--json'], { encoding: 'utf8' }).stdout);
const k = process.argv.indexOf('--course');
export const COURSE_NAME = k < 0 ? 'diffgeo-gr' : process.argv[k + 1];
if (!COURSES[COURSE_NAME]) { console.error(`unknown course ${COURSE_NAME}; courses: ${Object.keys(COURSES).join(', ')}`); process.exit(2); }
export const COURSE = COURSES[COURSE_NAME].dir;          // 'notes/<name>', relative to the repo root and to docs/
const MARK = '<!-- GENERATED by _port/convert/build.py';

// Without --course (and without --page, which names pages of one course: the default one unless --course is
// given), run the calling tool once per course of courses.py, one after the other, with the same arguments plus
// --course NAME; exit with a non-zero code if any run failed. Returns (and the tool goes on) when --course or
// --page is given. Call it at the top of the tool, before any work: eachCourse(import.meta.url).
export function eachCourse(toolUrl) {
  if (process.argv.includes('--course') || process.argv.includes('--page')) return;
  let rc = 0;
  for (const name of Object.keys(COURSES)) {
    console.log(`== ${name}`);
    const r = spawnSync(process.execPath, [fileURLToPath(toolUrl), '--course', name, ...process.argv.slice(2)], { stdio: 'inherit' });
    rc = rc || (r.status === null ? 1 : r.status);
  }
  process.exit(rc);
}

// slugs of every generated course page in docs/ ('index' = landing page), sorted
export function coursePages() {
  const root = path.join(REPO, 'docs', COURSE);
  const out = [];
  const walk = d => {
    for (const e of fs.readdirSync(d, { withFileTypes: true })) {
      const f = path.join(d, e.name);
      if (e.isDirectory()) walk(f);
      else if (e.name.endsWith('.html')) {
        const fd = fs.openSync(f, 'r'); const buf = Buffer.alloc(400); fs.readSync(fd, buf, 0, 400, 0); fs.closeSync(fd);
        if (buf.toString('utf8').includes(MARK)) out.push(path.relative(root, f).replace(/\.html$/, ''));
      }
    }
  };
  walk(root);
  return out.sort();
}

// `--page <slug>` (repeatable; a slug, or a prefix ending in '/'), else every page
export function selectPages(args, all = coursePages()) {
  const want = [];
  args.forEach((a, i) => { if (a === '--page' && args[i + 1]) want.push(args[i + 1].replace(/\.html$/, '')); });
  if (!want.length) return all;
  const sel = all.filter(s => want.some(w => s === w || (w.endsWith('/') && s.startsWith(w))));
  if (!sel.length) { console.error(`no page of ${COURSE} matches ${want.join(', ')}`); process.exit(2); }
  return sel;
}
export const hasFlag = (args, f) => args.includes(f);

// run fn(item) over items with n workers; results in input order
export async function pool(items, n, fn) {
  const res = new Array(items.length);
  let next = 0;
  await Promise.all(Array.from({ length: Math.min(n, items.length) }, async () => {
    while (next < items.length) { const i = next++; res[i] = await fn(items[i], i); }
  }));
  return res;
}

// after goto(): math typeset (course.js sets html.dg-math-ready) and the network idle again
export async function ready(page, timeout = 30000) {
  const ok = await page.waitForFunction(() => document.documentElement.classList.contains('dg-math-ready') || !window.MathJax, null, { timeout })
    .then(() => true, () => false);
  await page.waitForLoadState('networkidle').catch(() => {});
  await page.waitForTimeout(200);
  return ok;
}

export const url = (base, slug) => `${base}/${COURSE}/${slug}.html`;
