#!/usr/bin/env python3
"""Hand-written (DECISIONS D29, D36): add the course pages to the site's search index and sitemap.

    python3 _port/tools/post_render.py        (run by Quarto as the project's post-render script,
                                               and by _port/build.sh after a course-only build)

The course pages are complete HTML files that Quarto copies without rendering, so Quarto's own
docs/search.json and docs/sitemap.xml do not know them. For every course of _port/convert/courses.py, in its
order (Lyα DECISIONS L9), this script appends
  * the entries of notes/<course>/assets/search.json (written by the converter) to docs/search.json,
  * one <url> per course page to docs/sitemap.xml (same format as Quarto's; lastmod from
    notes/diffgeo-gr/assets/lastmod.json, which the converter keeps: the time the page's bytes last changed,
    so a rebuild without changes leaves the sitemap untouched; the file's mtime for a page not listed there).
Standard library only; reads only committed files; idempotent (course entries already present are
replaced, not duplicated). The output directory is QUARTO_PROJECT_OUTPUT_DIR when Quarto sets it, else docs/.
"""
import datetime, json, os, re, sys
from pathlib import Path

REPO = Path(__file__).resolve().parents[2]
sys.path.insert(0, str(REPO / '_port' / 'convert'))
import courses                                                  # noqa: E402  (standard library only)
MARK = '<!-- GENERATED by _port/convert/build.py'


def site_url() -> str:
    m = re.search(r'^\s*site-url:\s*"?([^"\s#]+)"?', (REPO / '_quarto.yml').read_text(encoding='utf-8'), re.M)
    if not m:
        raise SystemExit('post_render.py: no site-url in _quarto.yml')
    return m.group(1).rstrip('/')


def main() -> int:
    out = Path(os.environ.get('QUARTO_PROJECT_OUTPUT_DIR') or REPO / 'docs')
    if not out.is_absolute():
        out = REPO / out
    for name in courses.COURSES:
        add_course(out, courses.COURSES[name]['dir'])
    return 0


def add_course(out: Path, COURSE: str) -> None:
    src = REPO / COURSE
    if not (src / 'assets' / 'search.json').exists():
        print(f'post_render.py: {COURSE} has not been built (no assets/search.json); skipped')
        return

    # search index
    entries = json.loads((src / 'assets' / 'search.json').read_text(encoding='utf-8'))
    index_path = out / 'search.json'
    index = json.loads(index_path.read_text(encoding='utf-8')) if index_path.exists() else []
    index = [e for e in index if not e.get('href', '').startswith(COURSE + '/')] + entries
    index_path.write_text(json.dumps(index, ensure_ascii=False, indent=2) + '\n', encoding='utf-8')

    # sitemap: every generated page of the course
    pages = sorted(p for p in src.rglob('*.html') if MARK in p.read_text(encoding='utf-8')[:400])
    base = site_url()
    lm_path = src / 'assets' / 'lastmod.json'
    lastmod = json.loads(lm_path.read_text(encoding='utf-8')) if lm_path.exists() else {}
    urls = []
    for p in pages:
        when = lastmod.get(p.relative_to(src).as_posix())
        if not when:
            t = datetime.datetime.fromtimestamp(p.stat().st_mtime, tz=datetime.timezone.utc)
            when = f'{t.strftime("%Y-%m-%dT%H:%M:%S.")}{t.microsecond // 1000:03d}Z'
        urls.append(f'  <url>\n    <loc>{base}/{p.relative_to(REPO).as_posix()}</loc>\n'
                    f'    <lastmod>{when}</lastmod>\n  </url>\n')
    sm_path = out / 'sitemap.xml'
    if sm_path.exists():
        sm = sm_path.read_text(encoding='utf-8')
        sm = re.sub(r'  <url>\s*<loc>[^<]*/' + re.escape(COURSE) + r'/[^<]*</loc>.*?</url>\n', '', sm, flags=re.S)
    else:
        sm = '<?xml version="1.0" encoding="UTF-8"?>\n<urlset xmlns="http://www.sitemaps.org/schemas/sitemap/0.9">\n</urlset>\n'
    if '</urlset>' not in sm:
        raise SystemExit(f'post_render.py: {sm_path} has no </urlset>')
    sm = sm.replace('</urlset>', ''.join(urls) + '</urlset>', 1)
    if not sm_path.exists() or sm_path.read_text(encoding='utf-8') != sm:
        sm_path.write_text(sm, encoding='utf-8')
    print(f'post_render.py: {len(entries)} search entries and {len(urls)} sitemap addresses of {COURSE} added to {out.name}/')


if __name__ == '__main__':
    sys.exit(main())
